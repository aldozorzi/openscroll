export interface TechRelevanceInput {
  title: string;
  content?: string | null;
}

function normalize(value: string): string {
  return ` ${value
    .toLowerCase()
    .replace(/[^a-z0-9+#]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()} `;
}

function containsTerm(haystack: string, term: string): boolean {
  return haystack.includes(` ${normalize(term).trim()} `);
}

function countMatches(
  haystack: string,
  terms: readonly string[],
): number {
  const matches = new Set<string>();
  for (const term of terms) {
    if (containsTerm(haystack, term)) {
      matches.add(term);
    }
  }
  return matches.size;
}

export function isObviouslyOffTopicTitle(title: string): boolean {
  const normalized = normalize(title);
  return OFF_TOPIC_TITLE_TERMS.some((term) =>
    containsTerm(normalized, term),
  );
}

export function isTechRelevant(input: TechRelevanceInput): boolean {
  const title = normalize(input.title);
  if (isObviouslyOffTopicTitle(input.title)) {
    return false;
  }
  if (countMatches(title, TITLE_TERMS) > 0) {
    return true;
  }
  return countMatches(normalize(input.content ?? ''), CONTENT_TERMS) >= 3;
}
